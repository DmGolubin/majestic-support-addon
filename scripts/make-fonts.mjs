// Packs assets/fonts/*.woff2 (Golos Text, JetBrains Mono — SIL OFL 1.1, licenses next to them) into
// src/vencord/ui/fontData.ts as base64. The plugin loads them with the FontFace API from memory:
// no network request, and Discord's CSP (font-src) does not apply to ArrayBuffer sources.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const b64 = f => JSON.stringify(readFileSync(join(root, "assets/fonts", f)).toString("base64"));
const header = "/*\n * Vencord, a Discord client mod\n * Copyright (c) 2026 Vendicated and contributors\n * SPDX-License-Identifier: GPL-3.0-or-later\n */\n\n";
writeFileSync(join(root, "src/vencord/ui/fontData.ts"), header +
    "// Generated by scripts/make-fonts.mjs from assets/fonts/ (SIL OFL 1.1, see the OFL-*.txt there). Do not edit.\n" +
    `export const GOLOS_CYR = ${b64("golos-cyr.woff2")};\n` +
    `export const GOLOS_LAT = ${b64("golos-lat.woff2")};\n` +
    `export const MONO_CYR = ${b64("jbm-cyr.woff2")};\n` +
    `export const MONO_LAT = ${b64("jbm-lat.woff2")};\n`);
console.log("fontData.ts written");
